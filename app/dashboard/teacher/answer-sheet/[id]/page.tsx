"use client";

import { useEffect, useMemo, useState } from "react";
import Link from "next/link";
import { ArrowRight, FileText, Printer } from "lucide-react";
import { BRAND } from "@/lib/brand";
import { toEnglishDigits } from "@/lib/format";
import { renderAnswerBlockSvg } from "@/lib/omr/sheet-svg";
import { MAX_SHEET_QUESTIONS, MAX_STUDENT_CODE } from "@/lib/omr/standard-sheet";

type SheetData = {
  assignmentId: string;
  packageId: string;
  title: string;
  subject: string;
  grade: number | null;
  questionsPdfUrl: string | null;
  className: string;
  schoolName: string;
  questionCount: number;
  students: Array<{ id: string; name: string; code: number | null }>;
};

type Mode = "personal" | "shared";

function Sheet({
  data,
  studentName,
  studentCode,
}: {
  data: SheetData;
  studentName?: string;
  studentCode?: number | null;
}) {
  const svg = useMemo(
    () => renderAnswerBlockSvg({ questionCount: data.questionCount, seed: data.packageId, studentCode: studentCode ?? null }),
    [data.questionCount, data.packageId, studentCode]
  );
  return (
    <section className="answer-sheet mx-auto mb-6 bg-white p-6 shadow-sm print:mb-0 print:p-0 print:shadow-none" style={{ width: "186mm" }}>
      <header className="mb-4 flex items-start justify-between gap-4 border-b border-slate-200 pb-3">
        <div>
          <p className="text-lg font-black">{data.title}</p>
          <p className="text-xs font-bold text-slate-500">
            {data.schoolName} · {data.className} · {data.subject}
            {data.grade ? ` · الصف ${toEnglishDigits(data.grade)}` : ""}
          </p>
        </div>
        <p className="text-sm font-black text-slate-400">{BRAND.nameAr}</p>
      </header>

      <div className="mb-3 grid grid-cols-[1fr_auto] items-end gap-4 text-sm font-bold">
        <p>
          اسم الطالب:{" "}
          {studentName ? <span className="font-black">{studentName}</span> : <span className="inline-block w-64 border-b border-dotted border-slate-500" />}
        </p>
        {studentCode ? <p>رقمه في الكشف: <span className="font-black">{toEnglishDigits(studentCode)}</span></p> : null}
      </div>

      <ul className="mb-4 list-disc space-y-0.5 pr-5 text-xs font-bold text-slate-600">
        {!studentCode && <li>ظلّل رقمك في الكشف: خانة الآحاد، ثم خانة العشرات (اتركها إن كان رقمك أقل من ١٠).</li>}
        <li>ظلّل دائرة واحدة فقط لكل سؤال بقلم الرصاص، واملأ الدائرة كاملة.</li>
        <li>إذا غيّرت إجابتك فامسح الأولى جيدًا. لا تكتب ولا ترسم داخل المربعات السوداء أو حولها.</li>
      </ul>

      {/* Generated by our own code from numbers only — no user text inside. */}
      <div className="flex justify-center" dangerouslySetInnerHTML={{ __html: svg }} />
    </section>
  );
}

export default function AnswerSheetPage({ params }: { params: { id: string } }) {
  const [data, setData] = useState<SheetData | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [mode, setMode] = useState<Mode>("personal");

  useEffect(() => {
    let active = true;
    (async () => {
      try {
        const res = await fetch(`/api/teacher/class-package-assignments/${params.id}/answer-sheet`, { cache: "no-store" });
        const json = await res.json().catch(() => ({}));
        if (!res.ok || !json.success) throw new Error(json.error || "تعذر تجهيز ورقة الإجابة");
        if (!active) return;
        const loaded = json.data as SheetData;
        setData(loaded);
        if (!loaded.students.length) setMode("shared");
      } catch (err) {
        if (active) setError(err instanceof Error ? err.message : "تعذر تجهيز ورقة الإجابة");
      }
    })();
    return () => { active = false; };
  }, [params.id]);

  const markPrinted = () => {
    void fetch("/api/teacher/class-package-assignments", {
      method: "PATCH",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ assignmentId: params.id, action: "mark_printed" }),
    }).catch(() => undefined);
    window.print();
  };

  const studentsWithoutNumber = data?.students.filter((s) => !s.code || s.code > MAX_STUDENT_CODE) ?? [];
  const tooManyQuestions = (data?.questionCount ?? 0) > MAX_SHEET_QUESTIONS;

  return (
    <div className="min-h-screen bg-[#f7fafc] text-brand-navy print:bg-white" dir="rtl">
      <style>{`@page { size: A4; margin: 12mm; }
        @media print { body { -webkit-print-color-adjust: exact; print-color-adjust: exact; } .answer-sheet { break-after: page; } .answer-sheet:last-child { break-after: auto; } }`}</style>

      <div className="sticky top-0 z-10 border-b border-slate-100 bg-white/95 backdrop-blur print:hidden">
        <div className="mx-auto flex max-w-4xl flex-wrap items-center justify-between gap-3 px-4 py-3">
          <Link href="/dashboard/teacher" className="flex items-center gap-1 text-sm font-bold text-slate-500 hover:text-brand">
            <ArrowRight className="h-4 w-4" /> العودة
          </Link>
          {data && (
            <div className="flex flex-wrap items-center gap-2">
              <div className="flex rounded-xl border border-slate-200 p-0.5 text-xs font-extrabold">
                <button
                  onClick={() => setMode("personal")}
                  disabled={!data.students.length}
                  className={`rounded-lg px-3 py-1.5 disabled:opacity-40 ${mode === "personal" ? "bg-brand text-white" : "text-slate-500"}`}
                >
                  ورقة لكل طالب ({toEnglishDigits(data.students.length)})
                </button>
                <button
                  onClick={() => setMode("shared")}
                  className={`rounded-lg px-3 py-1.5 ${mode === "shared" ? "bg-brand text-white" : "text-slate-500"}`}
                >
                  نسخة واحدة للتصوير
                </button>
              </div>
              {data.questionsPdfUrl && (
                <a href={data.questionsPdfUrl} target="_blank" rel="noreferrer" className="flex items-center gap-1 rounded-xl border border-slate-200 px-3 py-2 text-xs font-extrabold text-slate-600 hover:text-brand">
                  <FileText className="h-4 w-4" /> ورقة الأسئلة
                </a>
              )}
              <button onClick={markPrinted} disabled={tooManyQuestions || !data.questionCount} className="flex items-center gap-1 rounded-xl bg-brand px-4 py-2 text-xs font-extrabold text-white disabled:opacity-50">
                <Printer className="h-4 w-4" /> طباعة أوراق الإجابة
              </button>
            </div>
          )}
        </div>
        {data && (
          <div className="mx-auto max-w-4xl space-y-1 px-4 pb-3 text-xs font-bold text-slate-500">
            <p>
              يقرأ {BRAND.nameAr} هذه الورقة بالكاميرا دون ذكاء اصطناعي. اطبع ورقة الأسئلة كالمعتاد، ويظلّل الطالب إجاباته في ورقة الإجابة.
              {mode === "personal" ? " كل ورقة مطبوع عليها اسم الطالب ورقمه مظللًا، فلا يحتاج الطالب لتظليل رقمه." : " صوّر هذه النسخة لكل الطلاب من نسخة نظيفة واحدة، لا تصوير من تصوير."}
            </p>
            {mode === "personal" && studentsWithoutNumber.length > 0 && (
              <p className="text-amber-700">
                {toEnglishDigits(studentsWithoutNumber.length)} طالب بلا رقم صالح (١–{toEnglishDigits(MAX_STUDENT_CODE)}): ستُطبع أوراقهم بلا رقم مظلل ويظللونه بأنفسهم.
              </p>
            )}
            {tooManyQuestions && <p className="text-danger">ورقة الإجابة تتسع لـ {toEnglishDigits(MAX_SHEET_QUESTIONS)} سؤالًا كحد أقصى.</p>}
          </div>
        )}
      </div>

      <main className="mx-auto max-w-4xl px-4 py-6 print:p-0">
        {error && <p className="rounded-xl border border-red-100 bg-red-50 p-4 text-sm font-bold text-red-700">{error}</p>}
        {!data && !error && <p className="text-center text-sm font-bold text-slate-400">جارٍ تجهيز أوراق الإجابة...</p>}
        {data && !data.questionCount && (
          <p className="rounded-xl border border-amber-100 bg-amber-50 p-4 text-sm font-bold text-amber-800">لم يُرفع مفتاح الإجابة لهذا الاختبار بعد.</p>
        )}
        {data && data.questionCount > 0 && !tooManyQuestions && (
          mode === "personal"
            ? data.students.map((student) => (
                <Sheet
                  key={student.id}
                  data={data}
                  studentName={student.name}
                  studentCode={student.code && student.code <= MAX_STUDENT_CODE ? student.code : null}
                />
              ))
            : <Sheet data={data} />
        )}
      </main>
    </div>
  );
}
